#!/usr/bin/env node
/**
 * Writes JS/config/supabase-config.js (git-ignored) from .env (git-ignored).
 *
 *   node tools/write-supabase-config.mjs
 *
 * The site has no build step, so browser code can't read .env directly; this turns the two public values
 * the browser needs into a tiny script. It refuses secret keys so they can't end up in frontend code.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const envPath = path.join(ROOT, '.env');
const outPath = path.join(ROOT, 'JS', 'config', 'supabase-config.js');

function fail(msg) {
  console.error('write-supabase-config: ' + msg);
  process.exit(1);
}

if (!fs.existsSync(envPath)) fail('.env not found. Copy .env.example to .env and fill in your project values.');

const env = {};
for (const line of fs.readFileSync(envPath, 'utf8').split(/\r?\n/)) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
  if (m && !line.trim().startsWith('#')) env[m[1]] = m[2].replace(/^["']|["']$/g, '');
}

const url = env.SUPABASE_URL;
const key = env.SUPABASE_PUBLISHABLE_KEY || env.SUPABASE_ANON_KEY;
if (!url || !/^https:\/\/[a-z0-9-]+\.supabase\.co\/?$/.test(url)) fail('SUPABASE_URL must look like https://<project-ref>.supabase.co');
if (!key) fail('SUPABASE_PUBLISHABLE_KEY is missing.');
if (/^sb_secret_/.test(key)) fail('That is a SECRET key. Only the publishable (anon) key may be used in browser code.');
if (/^eyJ/.test(key)) {
  // Legacy JWT keys: make sure it's the anon key, not service_role.
  try {
    const payload = JSON.parse(Buffer.from(key.split('.')[1], 'base64url').toString('utf8'));
    if (payload.role !== 'anon') fail(`That key has role "${payload.role}". Only the anon key may be used in browser code.`);
  } catch (e) {
    fail('Could not read that key. Use the publishable (anon) key from Project Settings → API.');
  }
} else if (!/^sb_publishable_/.test(key)) {
  fail('Unrecognised key format. Use the publishable key (sb_publishable_...) or the legacy anon key.');
}

// The Gemini key is a server secret for the Edge Function (supabase secrets set GEMINI_API_KEY=...).
// It must never sit next to browser config, so refuse to run if it is in .env.
if (Object.keys(env).some((k) => /GEMINI|GOOGLE_API|OPENAI/i.test(k) && env[k])) {
  fail('.env contains an AI provider key. Remove it: set it as a Supabase secret instead (supabase secrets set GEMINI_API_KEY=...). It must never reach browser code.');
}
// Payment secrets (Lemon Squeezy API key, webhook signing secret, Supabase service role) are server secrets too.
if (Object.keys(env).some((k) => /^(LS_|LEMON|SUPABASE_SERVICE|SERVICE_ROLE)/i.test(k) && env[k])) {
  fail('.env contains a payment or service-role secret. Remove it: set it as a Supabase secret instead (supabase secrets set LS_API_KEY=...). It must never reach browser code.');
}
const aiGuide = /^(1|true|yes)$/i.test(env.FOG_AI_GUIDE || '');
// Shows the Buy buttons. The checkout itself runs in the Edge Function payments-checkout (deploy it and set its secrets first).
const payments = /^(1|true|yes)$/i.test(env.FOG_PAYMENTS || '');

// Demo billing: sample data from the mock Lemon Squeezy store on the Billing page (never real, never unlocks anything).
const demoBilling = /^(1|true|yes)$/i.test(env.FOG_DEMO_BILLING || '');
// The site owner's user id (Supabase → Authentication → Users) to see the demo Revenue view.
const demoOwner = (env.FOG_DEMO_BILLING_OWNER || '').trim();
if (demoOwner && !/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(demoOwner)) fail('FOG_DEMO_BILLING_OWNER must be a user id (uuid) from Supabase → Authentication → Users.');

const config = { url: url.replace(/\/$/, ''), publishableKey: key };
if (aiGuide) config.aiGuide = true;
if (payments) config.payments = true;
if (demoBilling) config.demoBilling = true;
if (demoBilling && demoOwner) config.demoBillingOwner = demoOwner.toLowerCase();

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(
  outPath,
  `/* GENERATED by tools/write-supabase-config.mjs from .env — git-ignored, do not commit. */\n` +
    `window.FOG_SUPABASE_CONFIG = ${JSON.stringify(config, null, 2)};\n`
);
console.log('Wrote ' + path.relative(ROOT, outPath));
